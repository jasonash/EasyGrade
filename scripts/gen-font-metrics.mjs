/**
 * Generate src/shared/layout/helvetica-metrics.ts from pdfkit's own AFM data
 * so the shared layout engine measures text exactly as the PDF generator will.
 *
 *   node scripts/gen-font-metrics.mjs
 */
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const PDFDocument = require('pdfkit')
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// WinAnsi: ASCII, Latin-1 supplement, and the typographic extras pdfkit maps into 0x80-0x9F.
const EXTRAS = '€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ'
const codes = []
for (let c = 32; c <= 126; c++) codes.push(c)
for (let c = 160; c <= 255; c++) codes.push(c)
for (const ch of EXTRAS) codes.push(ch.codePointAt(0))

const doc = new PDFDocument({ autoFirstPage: false })
doc.fontSize(1000)
function table(font) {
  doc.font(font)
  const out = {}
  for (const code of codes) {
    out[code] = Math.round(doc.widthOfString(String.fromCodePoint(code)))
  }
  return out
}
function kerns(font, widths) {
  doc.font(font)
  const out = {}
  const chars = codes.map((c) => String.fromCodePoint(c))
  for (let i = 0; i < codes.length; i++) {
    for (let j = 0; j < codes.length; j++) {
      const pair = doc.widthOfString(chars[i] + chars[j])
      const kern = Math.round(pair - widths[codes[i]] - widths[codes[j]])
      if (kern !== 0) out[`${codes[i]},${codes[j]}`] = kern
    }
  }
  return out
}
const regular = table('Helvetica')
const bold = table('Helvetica-Bold')
const regularKerns = kerns('Helvetica', regular)
const boldKerns = kerns('Helvetica-Bold', bold)
doc.font('Helvetica')
const lineHeight1000 = Math.round(doc.currentLineHeight(true))

function emit(name, map, keyType) {
  const entries = Object.entries(map).map(([k, v]) => (keyType === 'number' ? `${k}:${v}` : `'${k}':${v}`))
  return `export const ${name}: Readonly<Record<${keyType}, number>> = {\n  ${entries.join(', ')}\n}\n`
}

const src = `/* Generated by scripts/gen-font-metrics.mjs from pdfkit ${require('pdfkit/package.json').version}. Do not edit. */
/* Advance widths in 1/1000 em, keyed by Unicode code point, for the WinAnsi character set. */

${emit('HELVETICA_WIDTHS', regular, 'number')}
${emit('HELVETICA_BOLD_WIDTHS', bold, 'number')}
/* Kerning adjustments in 1/1000 em keyed by "left,right" code points; pdfkit applies these when drawing. */
${emit('HELVETICA_KERNS', regularKerns, 'string')}
${emit('HELVETICA_BOLD_KERNS', boldKerns, 'string')}
/** pdfkit line height including the font's line gap, per 1pt of font size. */
export const HELVETICA_LINE_HEIGHT = ${lineHeight1000 / 1000}
`
writeFileSync(resolve(root, 'src/shared/layout/helvetica-metrics.ts'), src)
console.log(`wrote ${codes.length} widths per face, ${Object.keys(regularKerns).length}/${Object.keys(boldKerns).length} kern pairs; line height factor ${lineHeight1000 / 1000}`)
